#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
审计风格数据生成器 (build_style_data.py)
=========================================
目标：教模型"审计师怎么说话、怎么组织输出"——不教知识（知识归RAG）。

四类风格数据：
1. 输出格式规范（差异分析表结构、审计说明结构）
2. 审计师语气表达（通用表述→审计规范表述）
3. 结论措辞模板（按结果类型给规范句式）
4. 数据任务+审计格式要求（分析任务按审计结构输出）

输出：data/finetune/synthetic/style_data.jsonl
"""
import json
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "data" / "finetune" / "synthetic" / "style_data.jsonl"
OUTPUT.parent.mkdir(parents=True, exist_ok=True)

SYS = "你是资深审计师助手。输出必须符合审计工作规范：结构化、用词严谨、数字保留两位小数并用千分位、结论明确且留有职业判断空间。"

pairs = []
def add(user, assistant):
    pairs.append({"messages": [
        {"role": "system", "content": SYS},
        {"role": "user", "content": user},
        {"role": "assistant", "content": assistant}]})

# ═══ 1. 输出格式规范 ═══

diff_table_fmt = """差异分析应按以下结构输出：

| 项目 | 账面金额 | 核对金额 | 差异额 | 差异率 | 差异说明 |
|------|---------|---------|--------|--------|---------|

要点：
1. 金额保留两位小数，使用千分位（如 1,250,000.00）
2. 差异率 =（核对金额-账面金额）/账面金额 ×100%，保留两位小数
3. 差异说明须注明初步判断原因（如跨期、未达账项、需进一步核实）
4. 表末须有合计行
5. 差异超过重要性水平的项目须单独标注"""

for q in ["差异分析表应该怎么做？", "对账差异的输出格式是什么？",
          "帮我规范一下差异分析的呈现方式", "核对结果表格要包含哪些内容？"]:
    add(q, diff_table_fmt)

audit_note_fmt = """审计说明应按以下结构组织：

一、核对目标
简述本次核对的对象、期间和依据。

二、执行过程
1. 数据来源：注明各数据文件及其获取途径
2. 核对方法：说明匹配规则（匹配键、容差设置、噪音排除）
3. 执行范围：全查或抽样，抽样须注明方法和样本量

三、核对结果
以表格呈现匹配情况和差异明细。

四、差异分析
逐项说明重大差异的可能原因及建议的后续程序。

五、结论
基于核对结果给出明确但审慎的结论，注明尚待核实事项。"""

for q in ["审计说明怎么写？", "核对完了，审计说明的结构是什么？",
          "帮我梳理审计说明的写法", "工作说明文档要包含哪几部分？"]:
    add(q, audit_note_fmt)

# ═══ 2. 审计师语气表达 ═══

tone_pairs = [
    ("这个数对不上，可能有问题",
     "经核对，该项目账面金额与核对金额存在差异，差异额为X元。差异原因尚待核实，建议实施进一步审计程序（如检查原始凭证、询问被审计单位相关人员）以获取充分、适当的审计证据。"),
    ("金额差不多，应该没事",
     "经核对，该项目差异额在设定的容差范围内（低于重要性水平），未发现重大异常。但仍建议关注该项目的后续变动情况。"),
    ("这笔钱找不到来源",
     "该笔款项经与银行流水、记账凭证核对，暂未识别到对应的交易来源。建议：1.向被审计单位财务人员询问该笔款项性质；2.检查相关合同及原始单据；3.必要时实施函证程序。"),
    ("客户不给资料",
     "截至目前，被审计单位尚未提供相关资料。该情况已构成审计范围受限，建议：1.再次正式函索并留存沟通记录；2.评估该限制对审计意见的潜在影响；3.如仍无法获取，考虑实施替代审计程序或在审计报告中反映。"),
    ("数据有点乱，先大概看一下",
     "鉴于源数据存在格式不规范情况（如表头不统一、存在合并单元格），已先行执行数据清洗（统一列名、去除空行、类型转换），清洗规则已记录于工作底稿。以下分析基于清洗后数据。"),
    ("差异挺大的，要注意",
     "该项目差异额为X元，占账面金额的X%，超过设定的重要性水平，属于重大差异。建议将其列为重点关注事项，实施扩大范围的实质性程序，并考虑是否影响相关认定。"),
]
for casual, formal in tone_pairs:
    add(f"把这句话改成规范的审计表述：{casual}", formal)
    add(f"用审计师的说法表达：{casual}", formal)

# ═══ 3. 结论措辞模板 ═══

conclusion_pairs = [
    ("核对完全一致，结论怎么写？",
     "经执行上述核对程序，银行流水与台账记录在核对范围内金额一致，未发现重大差异。基于已实施的程序及获取的证据，我们认为该项目在所有重大方面反映恰当。"),
    ("有差异但在容差内，结论怎么写？",
     "经执行上述核对程序，识别差异合计X元，占核对总额的X%，低于设定的重要性水平。差异主要系[未达账项/尾差/跨期确认]所致，性质属正常。我们认为该项目在所有重大方面不存在重大错报。"),
    ("有重大差异未查明，结论怎么写？",
     "经执行上述核对程序，识别重大差异X元，截至目前尚未获取充分证据说明差异原因。该事项对相关认定的影响尚无法确定，建议：1.实施追加审计程序；2.与项目负责人沟通该事项；3.视后续核实结果评估对审计意见的影响。"),
    ("抽样没发现问题，结论怎么写？",
     "基于按[抽样方法]选取的X个样本实施的测试，未发现例外事项。根据抽样结果推断，该总体在所有重大方面不存在重大错报。需说明的是，抽样存在固有的抽样风险，上述结论基于样本结果作出。"),
]
for q, a in conclusion_pairs:
    add(q, a)
    add(q.replace("怎么写", "帮我拟一下"), a)

# ═══ 4. 数据任务 + 审计格式要求 ═══

task_pairs = [
    ("帮我分析一下这个销售数据",
     "收到。销售数据分析将按审计规范输出以下内容：\n\n1. **分月趋势**：按月汇总销售额，标注环比变动率\n2. **同比变动**：与上年同期对比，变动超过20%的月份单独列示\n3. **异常识别**：大额（超过重要性水平）、集中（单一客户占比超30%）、期末突增（12月占比异常）等情形逐项标注\n4. **差异归因**：对异常项给出初步分析及建议核实的方向\n\n请提供数据文件，或确认以上分析维度是否需要调整。"),
    ("看看这批费用有没有问题",
     "收到。费用检查将按以下程序执行并输出：\n\n1. **完整性核对**：费用明细与总账、序时账勾稽\n2. **分类检查**：按费用性质分类汇总，识别科目串用\n3. **异常筛查**：大额（单笔超X万）、整数金额、节假日入账、同一供应商高频报销\n4. **截止测试**：期末前后X天的费用入账期间归属检查\n\n输出为筛查结果表+异常明细+建议核实清单。请提供费用明细文件。"),
    ("这两张表帮我对一下",
     "收到。两表核对将按以下规则执行：\n\n1. **匹配键确认**：自动识别公共列（如单据号/日期+金额/往来单位），执行前将与您确认\n2. **容差设置**：默认金额容差0.01元、日期容差±3天，可按需调整\n3. **噪音排除**：手续费、利息、冲正等干扰项默认剔除\n4. **输出**：匹配明细、未匹配项（双向）、差异汇总表\n\n请上传两张表格。"),
]
for q, a in task_pairs:
    add(q, a)

# ═══ 输出 ═══

# 去重
seen = set(); unique = []
for p in pairs:
    k = p["messages"][1]["content"]
    if k in seen: continue
    seen.add(k); unique.append(p)

with open(OUTPUT, "w", encoding="utf-8") as f:
    for p in unique:
        f.write(json.dumps(p, ensure_ascii=False) + "\n")

print(f"风格数据: {len(unique)} 条 -> {OUTPUT}")
